CREATE OR REPLACE VIEW `data-aileron-482822-d0.monitoramento_carga.vw_drill_rotas` AS
SELECT
  `Data Planejada` AS Data,
  CONCAT(CAST(EXTRACT(YEAR FROM `Data Planejada`) AS STRING), '-S',
    LPAD(CAST(EXTRACT(ISOWEEK FROM `Data Planejada`) AS STRING), 2, '0')) AS AnoSemana,
  `Mes Ref` AS MesKey,
  Filial,
  Regiao,
  `Tipo Filial` AS Tipo,
  Transportador,
  Rota,
  -- Rota Planejada (do planejamento)
  CAST(NULL AS STRING) AS `Rota Planejada`,
  Placa,
  Motorista,
  `Tipo de Veiculo Padrao`,
  Status,
  `Status Rota`,
  `Status Rota Cor`,
  `Pedidos da Rota`,
  `Volumes da Rota`,
  `Peso Realizado (kg)` AS `Peso (kg)`,
  Paradas,
  Clientes,
  Entregues,
  `Insucessos Clean` AS Insucessos,
  Baixas,
  `KM Planejado`,
  `KM Realizado`,
  `Tempo Planejado (h)`,
  `Tempo Realizado (h)`,
  `Entrega Efetiva` AS `Entrega Efetiva Rota`,
  ocup_pedidos_rota AS `Ocupacao Pedidos Rota`,
  ocup_volumes_rota AS `Ocupacao Volumes Rota`,
  `Ocupacao Composta Rota`,
  `Flag Nao Planejada`,
  `Flag Sem Tempo`,
  `Flag Overtime`,
  `Flag Match Critico`,
  `Flag Entrega Critica`,
  `Match Temporal`,
  `Possui Planejado`,
  `Rota Concluida`
FROM `data-aileron-482822-d0.monitoramento_carga.vw_base_execucao`
ORDER BY `Data Planejada` DESC, Filial, Rota